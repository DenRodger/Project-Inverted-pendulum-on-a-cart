%% --- М4. Частотний аналіз ---

% 1. Задаємо аналітичну модель (приклад для стандартних параметрів, 
% підстав свої коефіцієнти k та a, якщо виводив рівняння, або скористайся лінеаризацією нижче)
% Припустимо, отримали: G = 1 / (s^2 - 25)
num = [1];        % Чисельник
den = [1 0 -25];  % Знаменник (s^2 + 0*s - 25)
G_pend = tf(num, den);

fprintf('--- Полюси розімкненої системи ---\n');
disp(pole(G_pend)); % Виведе полюси (один буде додатним!)

% 2. Побудова діаграми Боде
figure;
bode(G_pend);
grid on;
title('Діаграма Боде розімкненої системи маятника');

% 3. Розрахунок запасів стійкості замкненої системи (разом з PID кута)
% Твій PID для тета: C_theta = P_theta + D_theta*s
C_theta = pid(-25, 0, -5); 
L = G_pend * C_theta; % Контурна передатна функція

figure;
margin(L); % Побудує Боде із запасами стійкості для стабілізованого контуру

figure;
nyquist(L);
grid on;
title('Критерій Найквіста для замкненого контуру маятника');